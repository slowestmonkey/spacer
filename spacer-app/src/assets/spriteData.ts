// Ship with warning state - flickering lights, yellow tint
export const SHIP_WARNING: number[][] = SHIP_HEALTHY.map((row, y) =>
  row.map((pixel, x) => {
    // Add yellow warning sparks near antenna
    if ((x === 20 && y === 4) || (x === 28 && y === 5)) {
      return 17; // bright yellow spark
    }
    // Change green lights to orange warning
    if (pixel === 11 || pixel === 18) {
      return 8; // orange
    }
    return pixel;
  })
);

// Ship damaged - cracks, smoke, red damage marks
export const SHIP_DAMAGED: number[][] = SHIP_WARNING.map((row, y) =>
  row.map((pixel, x) => {
    // Add damage crack on body
    if (y >= 14 && y <= 22 && pixel === 4) {
      const crackLine = Math.floor((y - 14) * 0.8) + 17;
      if (Math.abs(x - crackLine) <= 1) {
        return 7; // dark red crack
      }
    }
    // Smoke particles near top
    if ((x === 30 && y === 6) || (x === 32 && y === 8) || (x === 31 && y === 4)) {
      return 14; // gray smoke
    }
    // More damage on fins
    if (pixel === 6 && ((x + y) % 7 === 0)) {
      return 7; // darker red
    }
    return pixel;
  })
);

// Ship critical - fire, heavy damage, sparks
export const SHIP_CRITICAL: number[][] = SHIP_DAMAGED.map((row, y) =>
  row.map((pixel, x) => {
    // Fire effects on the side
    if (y >= 12 && y <= 20 && (x >= 32 && x <= 36)) {
      if ((x + y) % 2 === 0 && pixel === 0) {
        return [8, 17, 16][Math.floor((x + y) / 2) % 3]; // fire colors
      }
    }
    // More cracks
    if (y >= 18 && y <= 26 && pixel === 4) {
      const crackLine2 = Math.floor((y - 18) * 0.6) + 18;
      if (Math.abs(x - crackLine2) <= 1) {
        return 7;
      }
    }
    // Sparks everywhere
    if (pixel === 11 || pixel === 18) return 17; // yellow sparks
    if (pixel === 5 && ((x * y) % 11 === 0)) return 17; // random sparks
    return pixel;
  })
);

// Ship destroyed - explosion debris
export const SHIP_DESTROYED: number[][] = Array(48).fill(null).map((_, y) =>
  Array(48).fill(null).map((__, x) => {
    const cx = 24, cy = 20;
    const dist = Math.sqrt((x - cx) ** 2 + (y - cy) ** 2);

    // Explosion core - bright white/yellow
    if (dist < 6) {
      if ((x + y) % 2 === 0) return 10; // white
      return 17; // yellow
    }

    // Inner explosion ring - orange/yellow
    if (dist >= 6 && dist < 10) {
      if ((x + y) % 2 === 0) return 17; // yellow
      return 8; // orange
    }

    // Outer explosion ring - red/orange
    if (dist >= 10 && dist < 14) {
      if ((x + y) % 3 === 0) return 16; // bright red
      if ((x + y) % 3 === 1) return 8; // orange
      return 0;
    }

    // Debris particles
    if (dist >= 14 && dist < 20) {
      if ((x * y) % 11 === 0) return 4; // teal ship piece
      if ((x * y) % 13 === 0) return 6; // red fin piece
      if ((x * y) % 17 === 0) return 17; // spark
      if ((x * y) % 19 === 0) return 14; // smoke
    }

    return 0;
  })
);

